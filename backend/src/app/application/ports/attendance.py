"""What the attendance use case needs from storage: the handoff tickets and the conversation's message log."""
from typing import Any, Protocol
from app.domain.identity import Identity, Operator


class HandoffRepository(Protocol):
    """Guarded updates return the updated ticket, or None when the ticket was not in the required state."""
    async def get(self, workspace_id: str, protocol: str) -> dict[str, Any] | None: ...
    async def active_for(self, who: Identity, conversation_id: str | None) -> dict[str, Any] | None: ...
    async def claim(self, workspace_id: str, protocol: str, operator: Operator) -> dict[str, Any] | None: ...
    async def operator_message(self, workspace_id: str, protocol: str, operator: Operator) -> dict[str, Any] | None: ...
    async def note(self, workspace_id: str, protocol: str, operator: Operator, content: str) -> dict[str, Any] | None: ...
    async def close(self, workspace_id: str, protocol: str, operator: Operator, resolution: str) -> dict[str, Any] | None: ...
    async def cancel(self, who: Identity, protocol: str) -> dict[str, Any] | None: ...


class MessageLog(Protocol):
    async def add_message(self, identity: Identity, conversation_id: str, role: str, content: str,
                          author_name: str | None = None) -> dict[str, Any]: ...
